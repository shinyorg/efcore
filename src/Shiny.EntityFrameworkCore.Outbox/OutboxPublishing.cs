using System.Diagnostics.CodeAnalysis;
using System.Text.Json;
using Microsoft.EntityFrameworkCore;
using Microsoft.EntityFrameworkCore.ChangeTracking;

namespace Shiny.EntityFrameworkCore.Outbox;

/// <summary>
/// The declarative half of enqueue: "every save of this entity type publishes an event". Built on a public
/// <c>ISaveChangesInterceptor</c>, so it needs no <c>DbContext</c> base class and no change to your save code.
/// </summary>
public static class OutboxPublishingExtensions
{
    /// <summary>
    /// Publishes outbox messages for <c>Added</c>/<c>Modified</c>/<c>Deleted</c> entities of the mapped types, in
    /// the <b>same transaction</b> as the <c>SaveChanges</c> that wrote them.
    /// <code>
    /// services.AddDbContext&lt;AppDbContext&gt;(o => o
    ///     .UseNpgsql(cs)
    ///     .AddOutboxPublishing(p => p.Publish&lt;Order&gt;(
    ///         ctx => new OrderChanged(ctx.Entity.Id, ctx.Operation),
    ///         OutboxOperations.Insert | OutboxOperations.Update,
    ///         partitionKey: ctx => ctx.Entity.Id.ToString())));
    /// </code>
    /// </summary>
    /// <remarks>
    /// An entity whose key is generated by the database (an identity column) has no real key until its row is
    /// written, so its event is built <b>after</b> that write. To keep both in one transaction the interceptor
    /// begins one when none is active, writes the deferred messages with a second <c>SaveChanges</c> pass, and
    /// commits. Inside your own transaction (or a <c>TransactionScope</c>) it simply joins it.
    /// </remarks>
    public static DbContextOptionsBuilder AddOutboxPublishing(this DbContextOptionsBuilder optionsBuilder, Action<OutboxPublishingBuilder> configure)
    {
        ArgumentNullException.ThrowIfNull(optionsBuilder);
        ArgumentNullException.ThrowIfNull(configure);

        var builder = new OutboxPublishingBuilder();
        configure(builder);
        if (builder.Publications.Count == 0)
            throw new ArgumentException("AddOutboxPublishing needs at least one Publish<T>(…) registration.", nameof(configure));

        return optionsBuilder.AddInterceptors(new OutboxPublishingInterceptor([.. builder.Publications]));
    }

    /// <inheritdoc cref="AddOutboxPublishing(DbContextOptionsBuilder, Action{OutboxPublishingBuilder})"/>
    public static DbContextOptionsBuilder<TContext> AddOutboxPublishing<TContext>(this DbContextOptionsBuilder<TContext> optionsBuilder, Action<OutboxPublishingBuilder> configure)
        where TContext : DbContext
        => (DbContextOptionsBuilder<TContext>)((DbContextOptionsBuilder)optionsBuilder).AddOutboxPublishing(configure);
}

/// <summary>Collects the <c>Publish&lt;T&gt;</c> registrations for <c>AddOutboxPublishing</c>.</summary>
public sealed class OutboxPublishingBuilder
{
    internal List<IOutboxPublication> Publications { get; } = [];

    /// <summary>
    /// Publishes an event for each saved entity assignable to <typeparamref name="T"/>.
    /// </summary>
    /// <param name="eventFactory">
    /// Builds the event. Return <c>null</c> to publish nothing for that save — the hook for "only when the status
    /// actually changed" (<c>ctx.Entry.Property(x =&gt; x.Status).IsModified</c>). Serialized by its runtime type.
    /// </param>
    /// <param name="operations">Which change-tracker operations publish. Defaults to all of them.</param>
    /// <param name="partitionKey">
    /// The ordering scope for the message. Return the aggregate id to make every event for one aggregate strictly
    /// ordered (with <see cref="OutboxOptions.OrderedPartitions"/> on).
    /// </param>
    [RequiresUnreferencedCode("Serializes the event object with reflection. Enqueue explicitly with a JsonTypeInfo in a trimmed or AOT application.")]
    [RequiresDynamicCode("Serializes the event object with reflection. Enqueue explicitly with a JsonTypeInfo in a trimmed or AOT application.")]
    public OutboxPublishingBuilder Publish<T>(
        Func<OutboxPublishContext<T>, object?> eventFactory,
        OutboxOperations operations = OutboxOperations.All,
        Func<OutboxPublishContext<T>, string?>? partitionKey = null) where T : class
    {
        ArgumentNullException.ThrowIfNull(eventFactory);
        if ((operations & OutboxOperations.All) == OutboxOperations.None)
            throw new ArgumentException("Publish<T> needs at least one operation to publish on.", nameof(operations));

        this.Publications.Add(new OutboxPublication<T>(eventFactory, operations, partitionKey));
        return this;
    }
}

/// <summary>What the event factory of <c>Publish&lt;T&gt;</c> sees about one saved entity.</summary>
public sealed class OutboxPublishContext<T> where T : class
{
    internal OutboxPublishContext(T entity, OutboxOperations operation, EntityEntry<T> entry, DbContext context)
    {
        this.Entity = entity;
        this.Operation = operation;
        this.Entry = entry;
        this.Context = context;
    }

    /// <summary>The entity. For an insert with a store-generated key, its key is already the real one.</summary>
    public T Entity { get; }

    /// <summary>Exactly one of <see cref="OutboxOperations.Insert"/>, <see cref="OutboxOperations.Update"/> or
    /// <see cref="OutboxOperations.Delete"/>.</summary>
    public OutboxOperations Operation { get; }

    /// <summary>
    /// The change-tracker entry. For updates and deletes (and inserts with client-side keys) the factory runs
    /// before the write, so <c>OriginalValues</c> and <c>IsModified</c> describe the change. For an insert whose key
    /// the database generates it runs after the write, when the entry is already <c>Unchanged</c>.
    /// </summary>
    public EntityEntry<T> Entry { get; }

    /// <summary>The context being saved.</summary>
    public DbContext Context { get; }
}

/// <summary>One <c>Publish&lt;T&gt;</c> registration, with the generic type erased for the interceptor.</summary>
interface IOutboxPublication
{
    bool Matches(EntityEntry entry, OutboxOperations operation);

    /// <summary>Builds the message, or null when the factory chose to publish nothing.</summary>
    OutboxMessage? Build(EntityEntry entry, OutboxOperations operation, string id, OutboxOptions options, DateTimeOffset now);
}

sealed class OutboxPublication<T>(
    Func<OutboxPublishContext<T>, object?> eventFactory,
    OutboxOperations operations,
    Func<OutboxPublishContext<T>, string?>? partitionKey) : IOutboxPublication where T : class
{
    public bool Matches(EntityEntry entry, OutboxOperations operation)
        => entry.Entity is T && operations.HasFlag(operation);

    [UnconditionalSuppressMessage("Trimming", "IL2026", Justification = "Reached only through Publish<T>, which is annotated RequiresUnreferencedCode.")]
    [UnconditionalSuppressMessage("AOT", "IL3050", Justification = "Reached only through Publish<T>, which is annotated RequiresDynamicCode.")]
    public OutboxMessage? Build(EntityEntry entry, OutboxOperations operation, string id, OutboxOptions options, DateTimeOffset now)
    {
        var entity = (T)entry.Entity;
        var ctx = new OutboxPublishContext<T>(entity, operation, entry.Context.Entry(entity), entry.Context);
        var evt = eventFactory(ctx);
        if (evt == null)
            return null;

        var payload = JsonSerializer.Serialize(evt, evt.GetType(), options.PayloadSerializerOptions);
        return OutboxDbContextExtensions.Create(
            id,
            OutboxDbContextExtensions.MessageTypeOf(evt.GetType()),
            payload,
            partitionKey?.Invoke(ctx),
            null,
            now);
    }
}
